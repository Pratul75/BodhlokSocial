// Embeds skills/*.md into src/skills.generated.ts, so the web app's bundle carries them
// without reading files at runtime. Run after editing a skill: pnpm --filter @bodh/agents skills
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "..", "skills");
export function bundledSource(): string {
  const skills = readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => ({ name: f.replace(/\.md$/, ""), text: readFileSync(join(dir, f), "utf8") }));
  return `// Generated by scripts/bundle-skills.ts from skills/*.md. Don't edit by hand.\nexport const BUNDLED_SKILLS: { name: string; text: string }[] = ${JSON.stringify(skills, null, 2)};\n`;
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(join(import.meta.dirname, "..", "src", "skills.generated.ts"), bundledSource());
  console.log("Wrote src/skills.generated.ts");
}
